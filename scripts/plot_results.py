#!/usr/bin/env python3
"""
Visualization script for the DRAM & Cache Memory Simulator.

Reads CSV output generated by `scripts/run_experiments.py` and produces
publication-quality Matplotlib figures in `results/plots/`.
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from typing import Dict, List

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def load_csv(path: Path) -> List[Dict[str, str]]:
    if not path.is_file():
        raise FileNotFoundError(f"CSV file not found: {path}")
    with path.open("r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def by_suite(rows: List[Dict[str, str]], suite: str) -> List[Dict[str, str]]:
    return [r for r in rows if r.get("suite") == suite]


def configure_style() -> None:
    plt.rcParams.update({
        "figure.figsize": (8, 5),
        "figure.dpi": 150,
        "axes.grid": True,
        "grid.alpha": 0.3,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "font.size": 10,
        "axes.titlesize": 12,
        "axes.titleweight": "bold",
    })


def plot_l1_miss_vs_capacity(rows: List[Dict[str, str]], out_dir: Path) -> None:
    data = sorted(by_suite(rows, "l1_capacity_sweep"), key=lambda r: int(r["l1_size"]))
    if not data:
        return
    sizes_kb = [int(r["l1_size"]) / 1024 for r in data]
    miss_rates = [float(r["l1_miss_rate_pct"]) for r in data]

    fig, ax = plt.subplots()
    ax.plot(sizes_kb, miss_rates, marker="o", linewidth=2, color="#1f77b4")
    ax.set_xscale("log", base=2)
    ax.set_xticks(sizes_kb)
    ax.set_xticklabels([f"{int(s)} KB" for s in sizes_kb])
    ax.set_title("L1 Miss Rate vs. Cache Capacity (4-way LRU, 256 KB Random)")
    ax.set_xlabel("L1 Cache Capacity (KB)")
    ax.set_ylabel("L1 Miss Rate (%)")
    fig.tight_layout()
    fig.savefig(out_dir / "01_l1_miss_rate_vs_capacity.png")
    plt.close(fig)


