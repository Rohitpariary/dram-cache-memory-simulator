def plot_lru_vs_fifo(rows: List[Dict[str, str]], out_dir: Path) -> None:
    data = by_suite(rows, "replacement_comparison")
    if not data:
        return
    grouped: Dict[str, List[Dict[str, str]]] = defaultdict(list)
    for r in data:
        grouped[r["replacement"].upper()].append(r)

    fig, ax = plt.subplots()
    for policy in ("LRU", "FIFO", "RANDOM"):
        if policy not in grouped:
            continue
        pts = sorted(grouped[policy], key=lambda r: int(r["l1_size"]))
        sizes = [int(r["l1_size"]) / 1024 for r in pts]
        misses = [float(r["l1_miss_rate_pct"]) for r in pts]
        ax.plot(sizes, misses, marker="o", linewidth=2, label=policy)

    if sizes := sorted({int(r["l1_size"]) / 1024 for r in data}):
        ax.set_xscale("log", base=2)
        ax.set_xticks(sizes)
        ax.set_xticklabels([f"{int(s)} KB" for s in sizes])
    ax.set_title("Replacement Policy Comparison: LRU vs. FIFO vs. Random (Hot-Set)")
    ax.set_xlabel("L1 Cache Capacity (KB)")
    ax.set_ylabel("L1 Miss Rate (%)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "05_lru_vs_fifo.png")
    plt.close(fig)


def plot_row_buffer_hit_rate(rows: List[Dict[str, str]], out_dir: Path) -> None:
    data = by_suite(rows, "workload_comparison")
    if not data:
        return
    names = [r["workload"] for r in data]
    hit_rates = [float(r["dram_row_hit_rate_pct"]) for r in data]

    fig, ax = plt.subplots(figsize=(10, 5))
    ax.bar(names, hit_rates, color="#9467bd", width=0.6)
    ax.set_title("DRAM Row-Buffer Hit Rate Across Synthetic Workloads (8 Banks, 8 KB Row)")
    ax.set_xlabel("Workload Type")
    ax.set_ylabel("Row-Buffer Hit Rate (%)")
    ax.set_ylim(0, 105)
    plt.xticks(rotation=30, ha="right")
    fig.tight_layout()
    fig.savefig(out_dir / "06_row_buffer_hit_rate_across_workloads.png")
    plt.close(fig)


def plot_dram_timing_vs_latency(rows: List[Dict[str, str]], out_dir: Path) -> None:
    data = sorted(by_suite(rows, "dram_timing_sweep"), key=lambda r: int(r["dram_tCAS"]))
    if not data:
        return
    labels = [f"tRCD/CAS/RP={r['dram_tRCD']}" for r in data]
    avg_cyc = [float(r["avg_cycles_per_request"]) for r in data]
    amat = [float(r["amat_cycles"]) for r in data]

    x = range(len(labels))
    width = 0.35
    fig, ax = plt.subplots()
    ax.bar([i - width / 2 for i in x], avg_cyc, width=width, label="Simulated Avg Cycles/Req")
    ax.bar([i + width / 2 for i in x], amat, width=width, label="AMAT (cycles)")
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels)
    ax.set_title("Simulated Latency vs. DRAM Timing Parameters (8 KB L1, 32 KB L2, Random)")
    ax.set_xlabel("DRAM Timing Configuration (cycles)")
    ax.set_ylabel("Latency (Cycles)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "07_dram_timing_vs_latency.png")
    plt.close(fig)


